#!/usr/bin/env python3
"""Ask a local Ollama model to write JUnit 5 tests for a Java source file.

The model output is a DRAFT. It lands in ai-generated/, which Maven never
compiles, so nothing generated reaches the test suite until a human reviews
it and promotes it into src/test/java by hand.

Usage (from the repo root):
    python3 scripts/generate_tests.py
    python3 scripts/generate_tests.py --model qwen3:8b --dry-run

Prerequisites: Ollama running locally (ollama serve) with the model pulled,
for example: ollama pull qwen2.5-coder:7b

Standard library only: no third-party packages needed.
"""

import argparse
import datetime
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_MODEL = os.environ.get("OLLAMA_MODEL", "qwen2.5-coder:7b")
DEFAULT_HOST = os.environ.get("OLLAMA_HOST", "http://localhost:11434")
DEFAULT_SOURCE = REPO_ROOT / "src/main/java/com/bharath/qa/pricing/PricingService.java"
DEFAULT_OUT = REPO_ROOT / "ai-generated/PricingServiceGeneratedTest.java"
PROMPT_TEMPLATE = Path(__file__).resolve().parent / "prompt_template.txt"
FENCED_JAVA = re.compile(r"```java\s*\n(.*?)```", re.DOTALL)


def build_prompt(source_path: Path) -> str:
    source = source_path.read_text()
    template = PROMPT_TEMPLATE.read_text()
    return template.replace("{source}", source)


def call_ollama(host: str, model: str, prompt: str) -> str:
    payload = json.dumps({"model": model, "prompt": prompt, "stream": False}).encode()
    request = urllib.request.Request(
        host.rstrip("/") + "/api/generate",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=600) as response:
            return json.loads(response.read())["response"]
    except urllib.error.URLError as exc:
        print(f"Cannot reach Ollama at {host}: {exc.reason}.", file=sys.stderr)
        print("Is Ollama running? Try: ollama serve  (and: ollama pull " + model + ")", file=sys.stderr)
        raise SystemExit(1)


def extract_java(text: str) -> str:
    match = FENCED_JAVA.search(text)
    return match.group(1).strip() if match else text.strip()


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate JUnit tests with a local Ollama model.")
    parser.add_argument("--model", default=DEFAULT_MODEL, help="Ollama model (default: %(default)s)")
    parser.add_argument("--host", default=DEFAULT_HOST, help="Ollama base URL (default: %(default)s)")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="Java source file to test")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Where to write the draft")
    parser.add_argument("--dry-run", action="store_true", help="Print the prompt and exit without calling Ollama")
    args = parser.parse_args()

    prompt = build_prompt(args.source)
    if args.dry_run:
        print(prompt)
        return

    print(f"Asking {args.model} to write tests for {args.source.name} ...")
    code = extract_java(call_ollama(args.host, args.model, prompt))
    header = (
        "// DRAFT - generated by Ollama model " + args.model + " on "
        + datetime.datetime.now().isoformat(timespec="seconds") + ".\n"
        "// REVIEW BEFORE PROMOTING: generated tests are drafts. Read every test,\n"
        "// run it, and only then move it into src/test/java by hand.\n\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header + code + "\n")
    print(f"Draft written to {args.out}")
    print("Next: review it, then promote the tests you trust into src/test/java and run: mvn test")


if __name__ == "__main__":
    main()
